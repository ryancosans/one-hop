#!/usr/bin/env bash
# Concatenate rules/*.md (sorted) into assembled outputs. Strips YAML frontmatter.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RULES="${ROOT}/rules"
ASSEMBLED="${ROOT}/assembled"
HARNESS="${ROOT}/harnesses"

strip_frontmatter() {
  awk 'BEGIN{fm=0} /^---$/ { fm++; if(fm==1) next; if(fm==2){fm=-1; next} } fm==-1 || fm==0 { print }'
}

mkdir -p "$ASSEMBLED" "$HARNESS"

{
  echo "<!-- Generated by tools/compose.sh — edit rules/ instead -->"
  echo
  for f in "$RULES"/*.md; do
    strip_frontmatter < "$f"
    echo
  done
} > "${ASSEMBLED}/AGENTS.md"

if [[ "${1:-}" == "--prompt" ]] || [[ "${1:-}" == "--all" ]]; then
  {
    echo "You are a coding agent. Follow these repository rules exactly."
    echo
    strip_frontmatter < "${RULES}/one-function-deep.md"
    echo
    strip_frontmatter < "${RULES}/no-single-line-wrappers.md"
    echo
    strip_frontmatter < "${RULES}/agent-implementation-discipline.md"
  } > "${HARNESS}/system-prompt.txt"
fi

if [[ "${1:-}" == "--all" ]]; then
  :
fi

echo "Wrote ${ASSEMBLED}/AGENTS.md"
if [[ -f "${HARNESS}/system-prompt.txt" ]]; then
  echo "Wrote ${HARNESS}/system-prompt.txt"
fi
